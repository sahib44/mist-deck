import { test, expect } from "@playwright/test";

test("shared heads receive judge alerts and chair clears judges only after backup and password", async ({ page }) => {
  page.on("dialog", dialog => dialog.accept());
  const password = process.env.SEED_PASSWORD;
  if (!password) throw new Error("SEED_PASSWORD is required");
  const login = async (email: string) => {
    await page.goto("/login");
    await page.getByLabel("Email", { exact: true }).fill(email);
    await page.getByLabel("Password", { exact: true }).fill(password);
    await page.getByRole("button", { name: "Sign in", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Operations overview" })).toBeVisible();
  };
  const logout = async () => { await page.getByRole("button", { name: "Sign out" }).click(); await expect(page.getByLabel("Email", { exact: true })).toBeVisible(); };
  await login("competitions@example.com");
  await page.goto("/judges");
  await expect(page.getByRole("button", { name: "Clear all judges", exact: true })).toHaveCount(0);
  await expect(page.getByRole("link", { name: "Saved lists", exact: true })).toHaveCount(0);
  await expect(page.getByRole("link", { name: "Contact tools", exact: true })).toHaveCount(0);
  await page.goto("/competitions/brackets");
  await page.locator(".pilot-card").filter({ hasText: "Brother's Improv" }).click();
  const competitionUrl = page.url();
  await expect(page.getByRole("button", { name: "Delete pilot" })).toHaveCount(0);
  for (const [name, email] of [["Inbox First Judge", "inbox-first@example.org"], ["Inbox Second Judge", "inbox-second@example.org"]]) {
    await page.getByRole("button", { name: "Add judge", exact: true }).click();
    await page.getByLabel("Name", { exact: true }).fill(name);
    await page.getByLabel("Email", { exact: true }).fill(email);
    await page.getByRole("dialog").getByRole("button", { name: "Add judge", exact: true }).click();
    await expect(page.getByRole("dialog")).toHaveCount(0);
  }
  await page.getByLabel("Select visible judges").check();
  await page.getByRole("button", { name: "Email selected (2)" }).click();
  await expect(page.getByRole("button", { name: "Remove Inbox First Judge", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Remove Inbox Second Judge", exact: true }).click();
  await page.getByLabel("Find or add a recipient").fill("Inbox Second");
  await page.locator(".recipient-options").getByRole("button", { name: /Inbox Second Judge/ }).click();
  await page.getByLabel("Find or add a recipient").fill("registration-extra@example.org");
  await page.getByLabel("Recipient name (optional)").fill("Registration Team");
  await expect(page.getByLabel("Add this person to judge directory")).not.toBeChecked();
  await page.getByRole("button", { name: "Add registration-extra@example.org", exact: true }).click();
  await expect(page.getByRole("button", { name: "Remove Registration Team", exact: true })).toBeVisible();
  await page.getByLabel("Campaign name", { exact: true }).fill("Inbox workflow campaign");
  await page.getByRole("button", { name: "Create draft & preview" }).click();
  await expect(page.getByRole("heading", { name: "Inbox workflow campaign" })).toBeVisible();
  await page.getByRole("button", { name: "Submit for approval" }).click();
  await page.getByRole("button", { name: "Approve campaign", exact: true }).click();
  await page.getByRole("button", { name: "Queue sandbox delivery" }).click();
  const campaignId = page.url().split("/campaigns/")[1];
  await expect.poll(async () => (await (await page.request.get(`/api/campaigns/${campaignId}`)).json()).status).toBe("completed");
  await page.goto("/campaigns");
  await page.getByLabel("Search outreach campaigns").fill("registration-extra@example.org");
  await expect(page.getByRole("row").filter({ hasText: "Inbox workflow campaign" })).toBeVisible();
  await page.getByLabel("Search outreach campaigns").fill("");
  await page.getByRole("button", { name: "Simulate incoming email" }).click();
  await page.getByLabel("Sender name", { exact: true }).fill("Inbox First Judge");
  await page.getByLabel("Sender email", { exact: true }).fill("inbox-first@example.org");
  await page.getByLabel("Subject", { exact: true }).fill("Yes, I can judge");
  await page.getByLabel("Message", { exact: true }).fill("Thanks for inviting me.");
  await page.getByRole("button", { name: "Receive sandbox email" }).click();
  await expect(page.locator(".conversation-row.unread")).toContainText("Inbox First Judge");
  await page.goto("/competitions");
  await expect(page.locator(".pilot-card").filter({ hasText: "Brackets" }).getByLabel("1 unread reply", { exact: true })).toBeVisible();
  await page.locator(".pilot-card").filter({ hasText: "Brackets" }).click();
  await expect(page.locator(".pilot-card").filter({ hasText: "Brother's Improv" }).getByLabel("1 unread reply", { exact: true })).toBeVisible();
  await page.goto(competitionUrl);
  await expect(page.locator(".pilot-judge").first()).toContainText("Inbox First Judge");
  await expect(page.locator(".pilot-judge").first().getByLabel("1 unread reply", { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Inbox First Judge", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Inbox First Judge", exact: true })).toBeVisible();
  await expect(page.getByText("Thanks for inviting me.")).toBeVisible();
  await page.goto("/competitions");
  await expect(page.locator(".pilot-card").filter({ hasText: "Brackets" }).locator(".unread-marker")).toHaveCount(0);
  await page.goto("/campaigns");
  await page.getByRole("button", { name: "Simulate incoming email" }).click();
  await page.getByLabel("Sender name", { exact: true }).fill("A New Sender");
  await page.getByLabel("Sender email", { exact: true }).fill("new-ticket@example.org");
  await page.getByLabel("Subject", { exact: true }).fill("General competitions question");
  await page.getByLabel("Message", { exact: true }).fill("I need help with a registration question.");
  await page.getByRole("button", { name: "Receive sandbox email" }).click();
  await expect(page.getByRole("heading", { name: "General competitions question", exact: true })).toBeVisible();
  await page.goto("/dashboard");
  await page.locator(".page-heading").getByRole("button", { name: /Notifications/ }).click();
  await expect(page.getByRole("dialog")).toContainText("Ticket email: A New Sender");
  await page.getByRole("button", { name: "Close dialog" }).click();
  await logout();
  await login("chair@example.com");
  await page.goto("/judges");
  await page.getByRole("button", { name: "Clear all judges", exact: true }).click();
  await page.getByRole("button", { name: "Yes, continue", exact: true }).click();
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Save backup and continue", exact: true }).click();
  expect((await download).suggestedFilename()).toContain("mist-deck-judges-backup");
  await page.getByLabel("Chair or director password").fill("incorrect-password");
  await page.getByRole("dialog").getByRole("button", { name: "Clear all judges", exact: true }).click();
  await expect(page.getByRole("dialog")).toContainText("Your password is incorrect.");
  await page.getByLabel("Chair or director password").fill(password);
  await page.getByRole("dialog").getByRole("button", { name: "Clear all judges", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await expect(page.getByText("No judges match these filters.")).toBeVisible();
  await expect(page.getByRole("link", { name: "Download the saved backup" })).toBeVisible();
  await page.screenshot({ path: "test-results/chair-clear-directory.png", fullPage: true });
});
